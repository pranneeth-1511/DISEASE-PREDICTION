import streamlit as st
import pytesseract
from PIL import Image
import appwrite_utils as aw
from tensorflow.keras.preprocessing.sequence import pad_sequences
import numpy as np

def predict_disease_from_text(text_input, res):
    """Predicts disease from text symptoms using LSTM"""
    max_len = 200 
    sequence = res['tokenizer'].texts_to_sequences([text_input])
    padded = pad_sequences(sequence, maxlen=max_len, padding='post', truncating='post')
    
    if res['lstm_model']:
        pred = res['lstm_model'].predict(padded, verbose=0)
        class_idx = np.argmax(pred)
        disease_name = res['label_encoder'].inverse_transform([class_idx])[0]
        confidence = np.max(pred)
        return disease_name, confidence
    return "Error", 0.0

def show_symptom_analysis(res):
    st.header("📝 Symptom & Clinical Note Analysis")
    st.markdown("Extract insights from medical notes using advanced NLP models.")
    
    if res['lstm_model'] is None:
        st.error("❌ Text model not found. Please run 'train_text.py' to generate the model files.")
        return

    # 2-Column Dashboard Layout
    main_col, side_col = st.columns([2, 1], gap="large")
    
    with main_col:
        st.markdown('<div class="card">', unsafe_allow_html=True)
        st.subheader("🔍 Input Data")
        
        tab_ocr, tab_manual = st.tabs(["📸 OCR Extraction", "⌨️ Manual Entry"])
        
        extracted_text = ""
        with tab_ocr:
            note_image = st.file_uploader("Upload Image", type=['jpg', 'png', 'jpeg'], key="note_uploader")
            if note_image:
                try:
                    with st.spinner("🔍 Running OCR..."):
                        img_ocr = Image.open(note_image)
                        st.image(img_ocr, caption="Uploaded Note", use_container_width=True)
                        extracted_text = pytesseract.image_to_string(img_ocr)
                        st.success("Text extracted successfully!")
                except Exception as e:
                    st.error(f"OCR Failed: {e}. (Ensure Tesseract is installed)")

        with tab_manual:
             st.info("Directly type or paste clinical notes below.")

        user_input = st.text_area("Clinical Notes / Symptoms", 
                                  value=extracted_text, 
                                  height=300,
                                  placeholder="Example: Patient presenting with persistent fatigue and joint pain...",
                                  help="The more detailed the notes, the more accurate the AI analysis.")
        
        btn_col, _ = st.columns([1, 1])
        with btn_col:
            predict_btn = st.button("🚀 Analyze Symptoms", use_container_width=True)
        st.markdown('</div>', unsafe_allow_html=True)

    with side_col:
        if predict_btn and user_input.strip():
            try:
                with st.spinner("Analyzing..."):
                    disease, conf = predict_disease_from_text(user_input, res)
                    
                    st.markdown(f"""
                    <div class="card" style="border-top: 4px solid var(--secondary);">
                        <div style="font-size: 0.85rem; color: var(--text-muted); text-transform: uppercase; font-weight: 700; margin-bottom: 8px;">Diagnosis Result</div>
                        <h2 style="color: var(--secondary); margin-top: 0; font-size: 1.8rem;">{disease}</h2>
                        <div style="margin: 16px 0;">
                            <span class="badge badge-success" style="font-size: 1rem; padding: 8px 16px;">
                                {conf*100:.1f}% Confidence
                            </span>
                        </div>
                        <p style="font-size: 0.9rem; color: var(--text-muted); line-height: 1.5;">
                            This result is generated by an LSTM-based Natural Language Processing model. 
                            It analyzes medical terminology and symptom patterns to identify the most likely condition.
                        </p>
                    </div>
                    """, unsafe_allow_html=True)
                    
                    # Store for saving
                    st.session_state.last_text_pred = {
                        "diagnosis": disease,
                        "confidence": float(conf),
                        "notes": user_input
                    }
            except Exception as e:
                st.error(f"Analysis Failed: {e}")
        
        if 'last_text_pred' in st.session_state:
            st.markdown('<div class="card" style="background: #F0FDFA; border: 1px solid #99F6E4;">', unsafe_allow_html=True)
            if st.button("💾 Save Final Result", use_container_width=True):
                try:
                    with st.spinner("Saving..."):
                        data = st.session_state.last_text_pred
                        data['type'] = "Symptom Analysis"
                        
                        if 'note_image' in locals() and note_image:
                            note_image.seek(0)
                            img_url, _ = aw.upload_medical_scan(st.session_state.user['localId'], note_image, note_image.name)
                            data['image_url'] = img_url

                        aw.save_diagnosis(st.session_state.user['localId'], data)
                        st.toast("✅ Analysis saved to cloud", icon="📈")
                        del st.session_state.last_text_pred
                        st.rerun()
                except Exception as e:
                    st.error(f"Save mission failed: {e}")
            st.markdown('</div>', unsafe_allow_html=True)
        
        if not (predict_btn or 'last_text_pred' in st.session_state):
            st.markdown("""
            <div class="card" style="border-style: dashed; opacity: 0.7; text-align: center; padding: 40px 20px;">
                <div style="font-size: 3rem; margin-bottom: 1rem;">🧬</div>
                <div style="color: var(--text-muted); font-weight: 500;">
                    Complete the clinical notes to generate an AI analysis report.
                </div>
            </div>
            """, unsafe_allow_html=True)
